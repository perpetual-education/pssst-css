/*
	The "Style Dictionary" slot — deliberately hand-written and tiny so nothing
	hides behind a tool. It reads the DTCG token JSON (our Token Studio stand-in)
	and writes plain CSS custom properties. That is the entire pipeline: a value
	typed once in a spec file arrives in the browser with no human retyping it.

	Run:  node build.js
	Reads:  tokens/brand-*.json  +  tokens/semantic.json
	Writes: styles/tokens.css
*/

const fs = require('fs');
const path = require('path');

const TOKENS_DIR = path.join(__dirname, 'tokens');
const OUT_FILE = path.join(__dirname, 'styles', 'tokens.css');

const BRANDS = ['ocean', 'forest', 'ember'];
const DEFAULT_BRAND = 'ocean';

function readJson(file) {
	return JSON.parse(fs.readFileSync(path.join(TOKENS_DIR, file), 'utf8'));
}

/*
	Flatten a nested DTCG object into { 'fill-primary': '{ramp.50}' } pairs.
	A node is a token when it has a $value; otherwise it is a group we recurse into.
	Keys starting with _ (like _comment) are skipped.
*/
function flatten(node, prefix, out) {
	for (const key of Object.keys(node)) {
		if (key.startsWith('_')) {
			continue;
		}

		const value = node[key];
		const name = prefix ? `${prefix}-${key}` : key;

		if (value && typeof value === 'object' && '$value' in value) {
			out[name] = value.$value;
		} else if (value && typeof value === 'object') {
			flatten(value, name, out);
		}
	}

	return out;
}

/*
	Resolve a DTCG alias like "{ramp.50}" against a brand's flattened primitives.
	Primitives are keyed 'ramp-50' after flattening, so we swap the dots for dashes.
	Non-alias values pass through untouched.
*/
function resolve(value, primitives) {
	const match = /^\{(.+)\}$/.exec(value);

	if (!match) {
		return value;
	}

	const key = match[1].replace(/\./g, '-');

	if (!(key in primitives)) {
		throw new Error(`Unresolved token reference: ${value}`);
	}

	return primitives[key];
}

/*
	One declaration per token, pairing its light and dark rungs into a single
	light-dark() value. The browser picks between them by the used color-scheme,
	which the [data-mode] wiring below drives — so a token's two values live on
	one line and there is no separate dark block to restate (and nothing to
	silently stomp it). This is the model derek-thomas-wood-website is migrating to.
*/
function declarationsFor(brand, semantic) {
	const primitives = flatten(readJson(`brand-${brand}.json`), '', {});
	const light = flatten(semantic.light, '', {});
	const dark = flatten(semantic.dark, '', {});

	return Object.keys(light).map(function (name) {
		const lightValue = resolve(light[name], primitives);
		const darkValue = resolve(dark[name], primitives);

		return `\t--${name}: light-dark(${lightValue}, ${darkValue});`;
	});
}

function block(selector, lines) {
	return `${selector} {\n${lines.join('\n')}\n}\n`;
}

function build() {
	const semantic = readJson('semantic.json');
	const blocks = [];

	// :root = default brand, and it opts the document into light-dark() by
	// declaring color-scheme. The mode toggle overrides color-scheme per branch;
	// absent [data-mode] = 'light dark' = follow the OS.
	blocks.push(block(':root', [
		'\tcolor-scheme: light dark;'
	].concat(declarationsFor(DEFAULT_BRAND, semantic))));

	// The mode axis is now one line each — it only flips color-scheme, and every
	// token's light-dark() re-resolves. No per-mode token blocks.
	blocks.push(block("[data-mode='light']", ['\tcolor-scheme: light;']));
	blocks.push(block("[data-mode='dark']", ['\tcolor-scheme: dark;']));

	// One block per non-default brand — each carries the full light-dark() set.
	for (const brand of BRANDS) {
		if (brand === DEFAULT_BRAND) {
			continue;
		}

		blocks.push(block(`[data-brand='${brand}']`, declarationsFor(brand, semantic)));
	}

	const header = '/*\n\tGENERATED by build.js — do not edit by hand.\n\tEdit tokens/*.json and re-run: node build.js\n*/\n\n';
	fs.writeFileSync(OUT_FILE, header + blocks.join('\n'));

	console.log(`Wrote ${OUT_FILE} — ${BRANDS.length} brands, light-dark() per token.`);
}

build();
